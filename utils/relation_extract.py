# utils/relation_extract.py
"""墨码写作 - AI 提取人物关系（纯逻辑，无 Qt、无网络）

从章节正文里找"明确出现的人物关系"，输出结构化数据供 UI 勾选。
"""
from __future__ import annotations

import json
import re
from typing import List, Dict


# 允许的关系词（约束 AI 输出，避免自由发挥）
ALLOWED_RELATIONS = [
    "师父", "师傅", "老师", "恩师",
    "徒弟", "弟子", "学生",
    # 同门关系统一用"同门"——"师兄/师姐/师弟/师妹"涉及入门先后，
    # 所有模型都容易张冠李戴（把"苏晚棠是李长生的师姐"当合法输出）
    "同门",
    "父亲", "母亲", "父母", "儿子", "女儿",
    "哥哥", "姐姐", "弟弟", "妹妹",
    "祖父", "祖母", "孙子", "孙女",
    "挚友", "好友", "朋友", "闺蜜",
    "宿敌", "仇人", "敌人", "对手", "死敌",
    "妻子", "丈夫", "爱人", "恋人", "未婚妻", "未婚夫",
]


_PROMPT = """你是一位小说编辑助手。请从下面的章节正文里，找出**明确出现的人物关系**。

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
【硬约束 1 · 方向】
"from" 必须填**主动称呼 / 处于晚辈或下属位置**的一方。
"to" 必须填**被称呼 / 处于长辈或上级位置**的一方。
"rel" 是 **from 对 to 的称呼**。

用"X 称呼 Y 为 [rel]"来验证方向：
  例 1：林墨管李长生叫"师父"
    ✓ {{"from": "林墨", "rel": "师父", "to": "李长生"}}
    ✗ {{"from": "李长生", "rel": "师父", "to": "林墨"}}   方向反

  例 2：苏晚棠、方知有是同门
    ✓ {{"from": "方知有", "rel": "同门", "to": "苏晚棠"}}
    ✓ {{"from": "苏晚棠", "rel": "同门", "to": "方知有"}}
       （"同门"是对称关系，两个方向都合理，取一条就够，不要两个都输出）

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
【硬约束 2 · 关系词必须和 to 匹配（最易出错）】

关系词分三类。输出前必须自问"这词用在 to 身上成立吗？"。

▶ 长辈 / 上级类（to 是长辈时用）：
   师父 / 师傅 / 老师 / 恩师 / 师叔 / 掌门
   → 只有"晚辈称呼长辈"才用这些词。
   → 如果 to 是"李长生（师父）"，rel 只能用上面这些；
     不能用"师姐""师弟""师兄""师妹"。

▶ 晚辈 / 同级 / 下属类（to 是同级或晚辈时用）：
   弟子 / 徒弟 / 学生 / 儿子 / 女儿
   同门
   下属 / 随从 / 仆人
   → 同门关系一律用"同门"，不要用"师兄/师姐/师弟/师妹"
   → 用这些词前，确认 to 确实处于"同级"或"晚辈"位置。

▶ 对称类（双方地位对等，方向随意）：
   挚友 / 好友 / 宿敌 / 仇人 / 敌人 / 对手
   妻子 / 丈夫 / 恋人 / 爱人 / 兄弟 / 姐妹

【关键规则 2.1 · 只选"原文出现过的词"】
"rel" 必须**在正文里出现过**，不许自作主张升级或降级。
  ✗ 原文写"一起在青锋山读书" → 不许升级成"挚友"
    （正确做法：不输出这条，或输出"同门"仅当正文出现过"同门"）
  ✗ 原文写"关系不好" → 不许升级成"宿敌"
  ✗ 原文写"三人并称青锋三杰" → 不许升级成"挚友"

【关键规则 2.1.5 · 严禁使用的词】
以下四个词**绝对不要出现在输出里**（任何情况下）：
  师兄 / 师姐 / 师弟 / 师妹
它们表达的是"同门 + 入门先后"两件事，模型容易张冠李戴。
遇到同门关系一律用"同门"，忽略谁年长谁年幼。

【关键规则 2.2 · 主语和关系词的所属】
当正文同时出现多个角色时，不要张冠李戴。
  正文："方知有、苏晚棠都是李长生的弟子"
    ✓ {{"from": "方知有", "rel": "弟子", "to": "李长生"}}
    ✓ {{"from": "苏晚棠", "rel": "弟子", "to": "李长生"}}
    ✗ 同门关系不能对长辈用（"同门"和"师父"是两回事）

正反例对照（关键！）：
  正文："方知有、苏晚棠、沈无咎三人都是李长生的弟子"
    ✓ {{"from": "方知有", "rel": "弟子", "to": "李长生"}}
    ✓ {{"from": "苏晚棠", "rel": "弟子", "to": "李长生"}}
    ✓ {{"from": "沈无咎", "rel": "弟子", "to": "李长生"}}

  正文："方知有、苏晚棠、沈无咎三人是同门"
    ✓ 三条边都用"同门"：
      方知有 —[同门]→ 苏晚棠
      方知有 —[同门]→ 沈无咎
      苏晚棠 —[同门]→ 沈无咎

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
【硬约束 3 · 明确写出，或能从相邻句子明确推断】

允许 A：正文直接写了称谓
  例："他是我师父" / "这是我师弟" / "她是我妻子"

允许 B：相邻一句话里说清了从属关系
  例："方知有、苏晚棠、沈无咎三人都是李长生的弟子"
    → 三条关系都成立（三人 → 李长生，弟子）
  例："沈无咎叛出师门"
    → 沈无咎 → 李长生（弟子）；这是"叛出师门"能明确推出的

不允许：靠整章印象的推测
  ✗ "并称""齐名""三人一起读书" —— 这不等于"挚友"
  ✗ "关系不好" —— 这不等于"宿敌"
  ✗ "潜在的同情者""背叛者" —— 描述性短语不算关系
  ✗ "三人一起在青锋山读书" —— 除非同一句里还有
     "同门""师兄弟""一起拜师"等具体称谓，否则不输出

"evidence" 必须是**原文原句**（不超过 30 字），不能为空。
  找不到支撑这条关系的原句，就不要输出这条。
  输出前逐条自检：这条的 evidence 是不是空字符串？
  如果是空，删掉这条。

【关键规则 3.1 · 宁缺毋滥，但别漏掉明确的】
如果一句话里明说了"X、Y、Z 都是李长生的弟子"，就输出 3 条，
不要因为"X 没单独提过"就漏掉。
只有同门情谊、没有明确师承的（比如"并称三杰"），不输出。

【关键规则 3.2 · 同一关系只输出一次】
同一对人物之间的关系**只输出一次**，不要：
  ✗ 既输出"X —[弟子]→ Y"又输出"Y —[师父]→ X"（同一关系的两种方向）
  ✗ 既输出"X —[同门]→ Y"又输出"Y —[同门]→ X"（对称关系的两个方向）

去重规则：保留**方向更明确**的那条（弟子/师父保留弟子那条）。
同门/挚友/宿敌这类对称关系，**只保留一条**（任选方向）。

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
【硬约束 4 · 改名去重】
如果正文明确写了：
  · "X 就是 Y"
  · "X 本名 Y / 化名 Y / 改叫 Y"
  · "X 叛出后改名 Y"
那么输出关系时**统一用其中一个名字**（优先用正文当前章节主要使用的那个），
同一个人的两个名字只输出一次。

例：正文说"赵无咎本名沈无咎，叛出师门后改名"
  ✓ 只输出一条：方知有 —[同门]→ 赵无咎
  ✗ 不要同时输出：
       方知有 —[同门]→ 沈无咎
       方知有 —[同门]→ 赵无咎

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
【输出要求】
- 只输出 JSON，不要任何解释，不要 markdown 代码块标记
- 格式严格为：
{{
  "relations": [
    {{"from": "人物A", "rel": "关系", "to": "人物B", "evidence": "原文原句"}}
  ]
}}
- "rel" 从以下词表里选：
  {relations}
- 同一对人物只输出一次（取最明确的那次）
- 最多 20 条；没有任何关系时返回空数组

【已有人物卡的角色名（含别名）】
{char_names}

请尽量把 "from" 和 "to" 都对应到上面的人物卡名字。
如果某个关系里的人物不在人物卡里，仍然输出，用正文里的原名。

【章节正文】
{text}"""


def build_prompt(text: str, char_names: List[str]) -> str:
    """构造提取 prompt。

    text 截断到 6000 字——提取"明确关系"不需要整章原文。
    """
    return _PROMPT.format(
        relations="、".join(ALLOWED_RELATIONS),
        char_names="、".join(char_names) or "（暂无）",
        text=(text or "")[:6000],
    )


def parse_response(text: str) -> List[Dict[str, str]]:
    """解析 AI 响应，返回 [{from, rel, to, evidence}, ...]。"""
    if not text:
        return []
    s = text.strip()
    if s.startswith("```"):
        s = re.sub(r"^```[a-zA-Z]*\s*\n?", "", s)
        s = re.sub(r"\n?```\s*$", "", s)

    data = None
    try:
        data = json.loads(s)
    except (json.JSONDecodeError, ValueError):
        # 慢路径：从杂文里抠出第一个 JSON 对象或数组
        m = re.search(r"[\{\[][\s\S]*[\}\]]", s)
        if m:
            try:
                data = json.loads(m.group(0))
            except (json.JSONDecodeError, ValueError):
                data = None

    # 兼容 AI 直接返回裸数组的情况
    # （漏掉 {"relations": [...]} 外层包装，小模型常犯）
    if isinstance(data, list):
        raw = data
    elif isinstance(data, dict):
        raw = data.get("relations") or []
    else:
        return []

    if not isinstance(raw, list):
        return []

    allowed = set(ALLOWED_RELATIONS)
    # 同义词归一（把 AI 的等价写法归到标准词）
    synonyms = {
        "师傅": "师父", "老师": "师父", "恩师": "师父",
        "徒弟": "弟子", "学生": "弟子",
        "挚友": "好友", "朋友": "好友", "闺蜜": "好友",
        "仇人": "敌人", "死敌": "敌人", "对手": "敌人",
        "爱人": "妻子", "恋人": "妻子",
        "未婚妻": "妻子", "未婚夫": "丈夫",
    }

    # 对称关系：A→B 和 B→A 是同一件事，只保留先出现的那条
    symmetric = {
        "同门", "好友", "敌人", "宿敌",
        "兄弟", "姐妹", "妻子", "丈夫",
    }

    # 明显不是"关系词"的模式（丢弃）
    _DROP_EXACT = {
        "潜在", "可能", "似乎", "也许", "大概", "陌生",
        "熟悉", "认识", "见过", "听说",
    }
    _DROP_SUFFIX = (
        "之谊", "情谊", "关系", "之间", "之间", "之感",
        "之交", "之情", "之义",  # 这些是"情谊"，不是"称谓"
    )

    def _valid_rel(rel: str) -> bool:
        """最基础的 sanity 检查：中文、2-6 字、不是描述性短语。

        允许词表外的关系（比如"主公""门客""道侣"），只是它们会
        归到"其他"颜色。这样用户不会因为词表不全而丢关系。
        """
        if not rel:
            return False
        # 长度 2-6 字
        if not (2 <= len(rel) <= 6):
            return False
        # 必须全是中文（允许"·"作连接符，比如"前世·恋人"）
        for ch in rel:
            if ch == "·":
                continue
            if not ("\u4e00" <= ch <= "\u9fff"):
                return False
        # 精确黑名单
        if rel in _DROP_EXACT:
            return False
        # 后缀黑名单（描述性短语）
        for suf in _DROP_SUFFIX:
            if rel.endswith(suf):
                return False
        return True

    out = []
    seen_exact = set()
    seen_symmetric = set()

    for it in raw[:30]:
        if not isinstance(it, dict):
            continue
        f = str(it.get("from", "") or "").strip()
        rel = str(it.get("rel", "") or "").strip()
        to = str(it.get("to", "") or "").strip()
        ev = str(it.get("evidence", "") or "").strip()
        if not (f and rel and to):
            continue
        if f == to:
            continue

        # 同义词归一
        rel = synonyms.get(rel, rel)

        # sanity 检查
        if not _valid_rel(rel):
            continue

        key = (f, rel, to)
        if key in seen_exact:
            continue
        seen_exact.add(key)

        if rel in symmetric:
            sym_key = (tuple(sorted([f, to])), rel)
            if sym_key in seen_symmetric:
                continue
            seen_symmetric.add(sym_key)

        out.append({"from": f, "rel": rel, "to": to, "evidence": ev})
    return out